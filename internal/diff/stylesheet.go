package diff

import (
	"fmt"
	"strings"
)

// StylesheetPath is where the app keeps a copy of Stylesheet, relative to
// the repository root; a test keeps it current.
const StylesheetPath = "frontend/src/diff.css"

// color is one of Inkuna's color tokens, with the value it has in the app
// (frontend/src/index.css) as the fallback for a page without the app's
// tokens, such as inkunactl's HTML.
type color struct{ token, value string }

func (color color) css() string { return fmt.Sprintf("var(%s, %s)", color.token, color.value) }

var (
	colorInk     = color{"--color-ink", "#dce4e5"}
	colorInkSoft = color{"--color-ink-soft", "#aab5b7"}
	colorMuted   = color{"--color-muted", "#819095"}
	colorAccent  = color{"--color-accent", "#ffb25b"}
	colorOK      = color{"--color-ok", "#6bcf9b"}
	colorWarn    = color{"--color-warn", "#ffd27a"}
	colorDanger  = color{"--color-danger", "#ff8c84"}
	colorAmber   = color{"--color-series-4", "#c98500"}
	colorViolet  = color{"--color-series-7", "#9085e9"}
)

// syntax gives each highlighting class its color. Every one keeps at least
// 4.5:1 contrast on the panel and on the added and deleted line tints
// below (the lowest, comments, is 4.61:1 on an added line).
var syntax = []struct {
	class string
	color color
	extra string
}{
	{"tok-keyword", colorViolet, ""},
	{"tok-type", colorAmber, ""},
	{"tok-meta", colorAmber, ""},
	{"tok-function", colorAccent, ""},
	{"tok-builtin", colorAccent, ""},
	{"tok-string", colorOK, ""},
	{"tok-number", colorWarn, ""},
	{"tok-constant", colorWarn, ""},
	{"tok-attribute", colorWarn, ""},
	{"tok-tag", colorDanger, ""},
	{"tok-comment", colorMuted, "font-style: italic;"},
	{"tok-operator", colorInkSoft, ""},
	{"tok-heading", colorAccent, "font-weight: 600;"},
	{"tok-inserted", colorOK, ""},
	{"tok-deleted", colorDanger, ""},
}

// Stylesheet is the CSS both renderers include: line tints for added and
// deleted lines, a stronger tint for what changed within a line, and the
// highlighting classes. It applies inside an element of class inkuna-diff;
// a renderer marks lines with line-added or line-deleted and a span that
// changed with changed.
func Stylesheet() string {
	var css strings.Builder
	css.WriteString("/* Generated by Stylesheet in internal/diff; edit it there. */\n")
	fmt.Fprintf(&css, ".inkuna-diff {\n  color: %s;\n}\n", colorInk.css())
	for _, line := range []struct {
		class string
		color color
	}{{"line-added", colorOK}, {"line-deleted", colorDanger}} {
		fmt.Fprintf(&css, ".inkuna-diff .%s {\n  background: color-mix(in srgb, %s 8%%, transparent);\n}\n", line.class, line.color.css())
		fmt.Fprintf(&css, ".inkuna-diff .%s .changed {\n  background: color-mix(in srgb, %s 24%%, transparent);\n}\n", line.class, line.color.css())
	}
	for _, rule := range syntax {
		fmt.Fprintf(&css, ".inkuna-diff .%s {\n  color: %s;\n", rule.class, rule.color.css())
		if rule.extra != "" {
			fmt.Fprintf(&css, "  %s\n", rule.extra)
		}
		css.WriteString("}\n")
	}
	return css.String()
}
